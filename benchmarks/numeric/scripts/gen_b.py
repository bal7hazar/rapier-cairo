#!/usr/bin/env python3
"""Generates packages/bench/tests/b_*.cairo: section B (own representations + cubit in the same kernels)."""
import pathlib
OUT = pathlib.Path(__file__).resolve().parent.parent / "packages/bench/tests"
A, B, C, SQ = 3.5, -1.25, 1.25, 1234.5678
VA, VB = (3.5, -1.25), (0.75, 2.125)
M = (0.36, 0.48, -0.8, -0.8, 0.6, 0.0, 0.48, 0.64, 0.6)
V3 = (3.5, -1.25, 2.0)

def sm(ty, bits):
    return lambda v: f"{ty} {{ mag: bb({round(abs(v)*(1<<bits))}), sign: {'true' if v < 0 else 'false'} }}"
def sg(ty, bits, suffix=""):
    return lambda v: f"{ty} {{ v: bb({round(v*(1<<bits))}{suffix}) }}"
def cub(bits):
    return lambda v: f"FixedTrait::new(bb({round(abs(v)*(1<<bits))}), {'true' if v < 0 else 'false'})"

REPRS = {
  "b_sm64":  dict(ty="Sm64",  use="use numbench::reprs::sm64::Sm64;", mk=sm("Sm64", 32), bits=32, raw=lambda e: f"(({e}).mag, ({e}).sign)"),
  "b_i64n":  dict(ty="I64n",  use="use numbench::reprs::i64n::I64n;", mk=sg("I64n", 32), bits=32),
  "b_i64b":  dict(ty="I64b",  use="use numbench::reprs::i64b::I64b;\nuse numbench::vecs::fused_i64b;", mk=sg("I64b", 32), bits=32, fused="fused_i64b"),
  "b_felt":  dict(ty="Fe",    use="use numbench::reprs::felt::Fe;\nuse numbench::vecs::fused_fe;", mk=sg("Fe", 32), bits=32, fused="fused_fe"),
  "b_sm128": dict(ty="Sm128", use="use numbench::reprs::sm128::Sm128;", mk=sm("Sm128", 64), bits=64),
  "b_cubit_f64":  dict(ty="Fixed", use="use cubit::f64::{Fixed, FixedTrait};\nuse numbench::reprs::cubit_fx::CubitF64Fx;", mk=cub(32), bits=32),
  "b_cubit_f128": dict(ty="Fixed", use="use cubit::f128::{Fixed, FixedTrait};\nuse numbench::reprs::cubit_fx::CubitF128Fx;", mk=cub(64), bits=64),
}

def gen(name, R):
    ty, mk = R["ty"], R["mk"]
    s = f"// GENERATED by scripts/gen_b.py - do not edit\n{R['use']}\nuse numbench::bb::{{bb, sink}};\nuse numbench::reprs::Fx;\nuse numbench::vecs::{{Vec2, Vec3, Mat3, dot2, cross2, length2, normalize2, mat3_mul_vec3}};\n\n"
    s += f"fn a() -> {ty} {{ {mk(A)} }}\nfn b() -> {ty} {{ {mk(B)} }}\nfn c() -> {ty} {{ {mk(C)} }}\nfn sq() -> {ty} {{ {mk(SQ if R['bits'] >= 32 else 200.5)} }}\n"
    s += f"fn va() -> Vec2<{ty}> {{ Vec2 {{ x: {mk(VA[0])}, y: {mk(VA[1])} }} }}\n"
    s += f"fn vb() -> Vec2<{ty}> {{ Vec2 {{ x: {mk(VB[0])}, y: {mk(VB[1])} }} }}\n"
    s += f"fn v3() -> Vec3<{ty}> {{ Vec3 {{ x: {mk(V3[0])}, y: {mk(V3[1])}, z: {mk(V3[2])} }} }}\n"
    names = ["m00","m01","m02","m10","m11","m12","m20","m21","m22"]
    s += f"fn m3() -> Mat3<{ty}> {{ Mat3 {{ " + ", ".join(f"{n}: {mk(v)}" for n, v in zip(names, M)) + " } }\n\n"
    T = []
    def t(n, body): T.append(f"#[test]\nfn {n}() {{ {body} }}\n")
    t("base_b1", "let x = a(); sink(x);")
    t("base_b2", "let x = a(); let y = b(); let _ = y; sink(x);")
    t("base_b2b", "let x = a(); let y = b(); let _ = x; let _ = y; sink(false);")
    t("base_v2", "let p = va(); let q = vb(); let _ = q; sink(p.x);")
    t("base_v1", "let p = va(); sink(p.x);")
    t("base_v1v", "let p = va(); sink(p);")
    t("base_m3", "let m = m3(); let v = v3(); let _ = m; sink(v);")
    t("b2_add_mixed_sign", "let x = a(); let y = b(); sink(x + y);")
    t("b2_add_same_sign", "let x = a(); let y = c(); sink(x + y);")
    t("b2_sub", "let x = a(); let y = b(); sink(x - y);")
    t("b2_mul", "let x = a(); let y = b(); sink(x * y);")
    t("b2_div", "let x = a(); let y = b(); sink(x / y);")
    t("b1_neg", "let x = a(); sink(-x);")
    t("b2b_lt_mixed_sign", "let x = a(); let y = b(); sink(x < y);")
    t("b2b_lt_same_sign", "let x = a(); let y = c(); sink(x < y);")
    t("b1_sqrt", "let x = sq(); sink(Fx::sqrt(x));")
    t("v2_dot2", "let p = va(); let q = vb(); sink(dot2(p, q));")
    t("v2_cross2", "let p = va(); let q = vb(); sink(cross2(p, q));")
    t("v1_length2", "let p = va(); sink(length2(p));")
    t("v1v_normalize2", "let p = va(); sink(normalize2(p));")
    t("m3_mat3_mul_vec3", "let m = m3(); let v = v3(); sink(mat3_mul_vec3(m, v));")
    if "fused" in R:
        f = R["fused"]
        t("v2_dot2_fused", f"let p = va(); let q = vb(); sink({f}::dot2(p, q));")
        t("v2_cross2_fused", f"let p = va(); let q = vb(); sink({f}::cross2(p, q));")
        t("v1_length2_fused", f"let p = va(); sink({f}::length2(p));")
        if f == "fused_i64b":
            t("v1_length2_wide_sqrt", f"let p = va(); sink({f}::length2_wide(p));")
            t("v1v_normalize2_wide_sqrt", f"let p = va(); sink({f}::normalize2_wide(p));")
            t("v1v_normalize2_fused", f"let p = va(); sink({f}::normalize2(p));")
            t("v1v_normalize2_fused_rsqrt", f"let p = va(); sink({f}::normalize2_rsqrt(p));")
        t("m3_mat3_mul_vec3_fused", f"let m = m3(); let v = v3(); sink({f}::mat3_mul_vec3(m, v));")
    # correctness checks (ignored by the runner: no baseline prefix)
    one = 1 << R["bits"]
    def near(expr, val, tol):
        lo, hi = mk(val - tol).replace("bb(", "(").replace("FixedTrait::new((", "FixedTrait::new(("), mk(val + tol).replace("bb(", "(")
        return f"{{ let e = {expr}; assert!({lo} < e); assert!(e < {hi}); }}"
    tol = 1e-6
    chk = []
    chk.append(near("(a() + b())", A + B, tol)); chk.append(near("(a() - b())", A - B, tol))
    chk.append(near("(a() * b())", A * B, tol)); chk.append(near("(a() / b())", A / B, tol))
    chk.append(near("(-a())", -A, tol)); chk.append("assert!(b() < a()); assert!(!(a() < b())); assert!(c() < a());")
    chk.append(near("Fx::sqrt(sq())", SQ ** 0.5, 1e-4))
    chk.append(near("dot2(va(), vb())", VA[0]*VB[0] + VA[1]*VB[1], tol))
    chk.append(near("cross2(va(), vb())", VA[0]*VB[1] - VA[1]*VB[0], tol))
    L = (VA[0]**2 + VA[1]**2) ** 0.5
    chk.append(near("length2(va())", L, 1e-4))
    chk.append("let n = normalize2(va()); " + near("n.x", VA[0]/L, 1e-4) + " " + near("n.y", VA[1]/L, 1e-4))
    r = [sum(M[3*i+j]*V3[j] for j in range(3)) for i in range(3)]
    chk.append("let r = mat3_mul_vec3(m3(), v3()); " + " ".join(near(f"r.{k}", r[i], 1e-6) for i, k in enumerate("xyz")))
    if "fused" in R:
        f = R["fused"]
        chk.append(near(f"{f}::dot2(va(), vb())", VA[0]*VB[0] + VA[1]*VB[1], tol))
        chk.append(near(f"{f}::cross2(va(), vb())", VA[0]*VB[1] - VA[1]*VB[0], tol))
        chk.append(near(f"{f}::length2(va())", L, 1e-4))
        if f == "fused_i64b":
            chk.append(near(f"{f}::length2_wide(va())", L, 1e-8))
            chk.append(f"let n = {f}::normalize2_rsqrt(va()); " + near("n.x", VA[0]/L, 1e-6) + " " + near("n.y", VA[1]/L, 1e-6))
        chk.append(f"let r = {f}::mat3_mul_vec3(m3(), v3()); " + " ".join(near(f"r.{k}", r[i], 1e-6) for i, k in enumerate("xyz")))
    T.append("#[test]\nfn check_correctness() {\n    " + "\n    ".join(chk) + "\n}\n")
    (OUT / f"{name}.cairo").write_text(s + "\n".join(T))

for n, R in REPRS.items():
    gen(n, R)
print("ok")
