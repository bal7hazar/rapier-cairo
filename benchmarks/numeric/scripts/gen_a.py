#!/usr/bin/env python3
"""Generates packages/bench/tests/a_*.cairo: section A (scalar ops of cubit / orion), same numeric inputs for every lib."""
import pathlib
OUT = pathlib.Path(__file__).resolve().parent.parent / "packages/bench/tests"
A, B, ANG, EXPIN, SQ = 3.5, 1.25, 0.7, 1.25, 1234.5678  # b is negated

LIBS = {
  "a_cubit_f64": dict(bits=32, ty="Fixed", mag="u64", hdr="use cubit::f64::{Fixed, FixedTrait};\nuse cubit::f64::math::trig;\n",
                      new="FixedTrait::new({m}, {s})", unscaled="FixedTrait::new_unscaled({m}, false)"),
  "a_cubit_f128": dict(bits=64, ty="Fixed", mag="u128", hdr="use cubit::f128::{Fixed, FixedTrait};\nuse cubit::f128::math::trig;\n",
                      new="FixedTrait::new({m}, {s})", unscaled="FixedTrait::new_unscaled({m}, false)"),
  "a_orion_fp16x16": dict(bits=16, ty="FP16x16", mag="u32", hdr="use orion::numbers::fixed_point::core::FixedTrait;\nuse orion::numbers::fixed_point::implementations::fp16x16::core::{FP16x16, FP16x16Impl, FP16x16Add, FP16x16Sub, FP16x16Mul, FP16x16Div, FP16x16PartialOrd, FP16x16Neg, FP16x16TryIntoU32};\nuse orion::numbers::fixed_point::implementations::fp16x16::math::trig;\n",
                      new="FixedTrait::<FP16x16, u32>::new({m}, {s})", unscaled="FixedTrait::<FP16x16, u32>::new_unscaled({m}, false)"),
  "a_orion_fp8x23": dict(bits=23, ty="FP8x23", mag="u32", hdr="use orion::numbers::fixed_point::core::FixedTrait;\nuse orion::numbers::fixed_point::implementations::fp8x23::core::{FP8x23, FP8x23Impl, FP8x23Add, FP8x23Sub, FP8x23Mul, FP8x23Div, FP8x23PartialOrd, FP8x23Neg, FP8x23TryIntoU32};\nuse orion::numbers::fixed_point::implementations::fp8x23::math::trig;\n",
                      new="FixedTrait::<FP8x23, u32>::new({m}, {s})", unscaled="FixedTrait::<FP8x23, u32>::new_unscaled({m}, false)", sq=200.5678),
  "a_orion_fp32x32": dict(bits=32, ty="FP32x32", mag="u64", hdr="use orion::numbers::fixed_point::core::FixedTrait;\nuse orion::numbers::fixed_point::implementations::fp32x32::core::{FP32x32, FP32x32Impl};\nuse cubit::f64::math::trig;\n",
                      new="FixedTrait::<FP32x32, u64>::new({m}, {s})", unscaled="FixedTrait::<FP32x32, u64>::new_unscaled({m}, false)", explicit=True),
}

def gen(name, L):
    one = 1 << L["bits"]
    ty = L["ty"]
    def mk(v, neg=False):
        return L["new"].format(m=f"bb({round(v*one)})", s="true" if neg else "false")
    sq = L.get("sq", SQ)
    s = f"// GENERATED by scripts/gen_a.py - do not edit\n{L['hdr']}use numbench::bb::{{bb, sink}};\n\n"
    s += f"fn a() -> {ty} {{ {mk(A)} }} // {A}\n"
    s += f"fn b() -> {ty} {{ {mk(B, True)} }} // -{B}\n"
    s += f"fn ang() -> {ty} {{ {mk(ANG)} }} // {ANG} rad\n"
    s += f"fn ex() -> {ty} {{ {mk(EXPIN)} }}\n"
    s += f"fn sq() -> {ty} {{ {mk(sq)} }} // {sq}\n\n"
    T = []
    def t(n, body): T.append(f"#[test]\nfn {n}() {{ {body} }}\n")
    t("base_b1", "let x = a(); sink(x);")
    t("base_b2", "let x = a(); let y = b(); sink(x); let _ = y;")
    t("base_b2b", "let x = a(); let y = b(); let _ = x; let _ = y; sink(false);")
    t("base_bi", f"let n: {L['mag']} = bb(7); sink({L['new'].format(m='n', s='false')});")
    t("base_bo", "let x = a(); sink(x.mag);")
    t("b2_add_mixed_sign", "let x = a(); let y = b(); sink(x + y);")
    t("b2_add_same_sign", "let x = a(); let y = ex(); sink(x + y);")
    t("b2_sub", "let x = a(); let y = b(); sink(x - y);")
    t("b2_mul", "let x = a(); let y = b(); sink(x * y);")
    t("b2_div", "let x = a(); let y = b(); sink(x / y);")
    t("b1_neg", "let x = a(); sink(-x);")
    t("b1_abs", "let x = b(); sink(x.abs());")
    t("b2b_lt", "let x = a(); let y = b(); sink(x < y);")
    t("b2b_lt_same_sign", "let x = a(); let y = ex(); sink(x < y);")
    t("b1_sqrt", "let x = sq(); sink(x.sqrt());")
    t("b1_sin", "let x = ang(); sink(trig::sin(x));")
    t("b1_sin_fast_lut", "let x = ang(); sink(trig::sin_fast(x));")
    t("b1_cos", "let x = ang(); sink(trig::cos(x));")
    t("b1_cos_fast_lut", "let x = ang(); sink(trig::cos_fast(x));")
    t("b1_atan", "let x = ang(); sink(trig::atan(x));")
    t("b1_atan_fast_lut", "let x = ang(); sink(trig::atan_fast(x));")
    t("b1_exp", "let x = ex(); sink(x.exp());")
    t("b1_floor", "let x = a(); sink(x.floor());")
    t("b1_round", "let x = a(); sink(x.round());")
    t("bi_from_int", f"let n: {L['mag']} = bb(7); sink({L['unscaled'].format(m='n')});")
    t("bo_to_int_u32", "let x = a(); let r: u32 = x.try_into().unwrap(); sink(r);")
    body = "\n".join(T)
    if L.get("explicit"):
        # Orion FP32x32 is a type alias of cubit::f64::Fixed: operator impls collide with cubit's own (E2313),
        # so Orion's impls are called explicitly.
        P = "orion::numbers::fixed_point::implementations::fp32x32::core::"
        for a, b in [("sink(x + y)", f"sink({P}FP32x32Add::add(x, y))"), ("sink(x - y)", f"sink({P}FP32x32Sub::sub(x, y))"),
                     ("sink(x * y)", f"sink({P}FP32x32Mul::mul(x, y))"), ("sink(x / y)", f"sink({P}FP32x32Div::div(x, y))"),
                     ("sink(-x)", f"sink({P}FP32x32Neg::neg(x))"), ("sink(x < y)", f"sink({P}FP32x32PartialOrd::lt(x, y))"),
                     ("let r: u32 = x.try_into().unwrap();", f"let r: u32 = {P}FP32x32TryIntoU32::try_into(x).unwrap();"),
                     ("x.abs()", "FP32x32Impl::abs(x)"), ("x.sqrt()", "FP32x32Impl::sqrt(x)"), ("x.exp()", "FP32x32Impl::exp(x)"),
                     ("x.floor()", "FP32x32Impl::floor(x)"), ("x.round()", "FP32x32Impl::round(x)")]:
            body = body.replace(a, b)
    (OUT / f"{name}.cairo").write_text(s + body)

for n, L in LIBS.items():
    gen(n, L)
print("ok")
